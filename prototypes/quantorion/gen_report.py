S("四、实现方式")
B("4.1 技术选型：Python 3.9，核心依赖pandas、tushare、fastapi、pydantic。")
B(
    "4.2 核心实现细节：涨停判断根据股票代码前缀确定涨停幅度（主板10%、创业板/"
    "科创板20%），比较当日涨跌幅是否达到阈值（含0.5%容差）。缩量判断比较最近"
    "交易日与前一日成交量，确保成交量递减，这是区分真连板与放量出货的关键。A股"
    "过滤仅保留代码前缀为00/60/30/68的股票。资金分配将总资金均分给所有符合条件"
    "的股票，按前日收盘价计算可买股数，向下取整到100的倍数。回测系统按自然周分组，"
    "每周一重置50万元，每日模拟买入-卖出，周终用收盘价估值。"
)
