# 3
S("三、设计方案")
B("3.1 策略核心逻辑")
B(
    "缩量连板策略基于以下市场规律：当一只股票连续多日涨停（连板）且成交量逐日"
    "递减（缩量）时，表明持股者惜售、买盘强劲，次日继续上涨的概率较高。具体条件："
)
BL("最近交易日涨幅 >= 涨停幅度（主板10%/双创20%）乘以99.5%（含0.5%容差）。")
BL("前一交易日同样满足涨停条件（构成连板）。")
BL("最近交易日成交量 < 前一交易日成交量（缩量）。")
BL("股票代码前缀为00/60/30/68（纯A股，排除北交所）。")
B("3.2 系统架构")
BL("数据层（tushare_client.py）：封装Tushare API，提供交易日历、行情数据、股票列表等接口，含内存缓存以减少API调用次数。")
BL("策略层（main.py）：实现缩量连板筛选逻辑，包括涨停判断、缩量判断、A股过滤、资金分配，支持CLI和HTTP API两种入口。")
BL("回测层（backtest_limitup_weekly.py）：按周独立回测，每周重置初始资金50万，模拟前日收盘买入-当日收盘卖出的完整交易流程。")
B("3.3 数据流")
B(
    "每日执行流程：用户输入(资金+日期) -> Tushare获取前两交易日全市场日线 -> "
    "涨停判断+缩量判断+A股过滤 -> 按成交量升序排列 -> 资金均分、按前日收盘价"
    "计算可买股数（取整100倍） -> 输出JSON。"
)

