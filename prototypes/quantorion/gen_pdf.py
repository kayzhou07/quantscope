# === 3 ===
title("三、设计方案")
body("3.1 策略核心逻辑")
body("缩量连板策略基于以下市场规律：当一只股票连续多日涨停（连板）且成交量逐日递减（缩量）时，表明持股者惜售、买盘强劲，次日继续上涨的概率较高。具体筛选条件：")
dot("最近交易日涨幅 >= 涨停幅度（主板10%/双创20%）乘以 99.5%（含0.5%容差）。")
dot("前一交易日同样满足涨停条件，构成连板。")
dot("最近交易日成交量 < 前一交易日成交量，构成缩量。")
dot("股票代码前缀为00/60/30/68，即纯A股，排除北交所。")

