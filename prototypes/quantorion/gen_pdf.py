dot("策略层（main.py）：实现缩量连板筛选逻辑，包括涨停判断、缩量判断、A股过滤、资金分配。支持CLI和HTTP API两种入口，集成FastAPI框架。")
dot("智能层（ai_sentiment.py + market_news.py）：DeepSeek AI情绪分析模块和新闻聚合模块。AI情绪分析市场氛围和逐股点评，新闻聚合从新浪财经等源获取快讯，AI自动生成每日收盘简报。所有智能输出仅用于展示，不参与选股决策。")
dot("展示层（Web UI）：QuantOrion金融级Web界面，深色/浅色双模式，响应式布局支持PC和移动端。包含市场全景面板（四大指数+涨跌分布）、AI收盘简报、财经要闻、回测数据看板、因子库可视化、实盘模拟交互区。")

